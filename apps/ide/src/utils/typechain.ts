import type { SilContractAbi } from "@/store/silver";

/**
 * HardKas TypeChain: Generates strongly-typed TypeScript SDK wrappers for SilverScript contracts.
 * Enables zero-boilerplate frontend integration with autocomplete, typed arguments, and KasWare/node execution.
 */

function toPascalCase(str: string): string {
  return str.replace(/(^\w|_\w)/g, (m) => m.replace("_", "").toUpperCase());
}

function tsTypeForSil(kind: string): string {
  switch (kind) {
    case "sig":
      return "string"; // account name or hex signature
    case "int":
      return "number | bigint";
    case "bool":
      return "boolean";
    case "pubkey":
      return "string | Uint8Array | number[]"; // address or 32-byte Schnorr pubkey
    case "bytes":
      return "string | Uint8Array | number[]";
    default:
      return "string | unknown";
  }
}

export function generateTypeChain(contract: SilContractAbi, sourcePath?: string): string {
  const className = toPascalCase(contract.name);

  // Generate param interfaces for each entry
  const entryInterfaces = contract.entries
    .map((e) => {
      const interfaceName = `${className}${toPascalCase(e.name)}Params`;
      const fields = e.params
        .map((p) => `  /** ${p.kind} parameter: ${p.name} */\n  ${p.name}: ${tsTypeForSil(p.kind)};`)
        .join("\n");
      return `/** Arguments for entrypoint '${e.name}' */
export interface ${interfaceName} {
${fields}
  /** Recipient address of the spending transaction output */
  to: string;
  /** Optional transaction sequence for relative timelocks */
  sequence?: string;
}`;
    })
    .join("\n\n");

  // Generate methods for each entrypoint
  const entryMethods = contract.entries
    .map((e) => {
      const interfaceName = `${className}${toPascalCase(e.name)}Params`;
      return `  /**
   * Calls entrypoint '${e.name}'${e.dispatchTag ? ` (dispatch tag #${e.dispatchTag})` : ""}.
   * @param params Typed parameters for this contract spend
   */
  async ${e.name}(params: ${interfaceName}): Promise<ContractSpendReceipt> {
    const args = [
${e.params
  .map((p) => {
    if (p.kind === "sig") {
      return `      { kind: "signature", account: params.${p.name} }`;
    } else if (p.kind === "int") {
      return `      { kind: "int", value: Number(params.${p.name}) }`;
    } else if (p.kind === "bool") {
      return `      { kind: "bool", value: Boolean(params.${p.name}) }`;
    } else {
      return `      { kind: "bytes", value: params.${p.name} }`;
    }
  })
  .join(",\n")}
    ];

    if (this.provider && typeof this.provider.spendContract === "function") {
      return this.provider.spendContract({
        address: this.address,
        contract: "${contract.name}",
        entry: "${e.name}",
        to: params.to,
        args,
        sequence: params.sequence
      });
    }

    throw new Error("No compatible provider found (KasWare or HardKas engine required)");
  }`;
    })
    .join("\n\n");

  return `/**
 * Auto-generated by HardKas TypeChain for Kaspa
 * Contract: ${contract.name}
 * Source: ${sourcePath ?? "contracts/" + contract.name + ".sil"}
 * Generated at: ${new Date().toISOString()}
 * 
 * DO NOT EDIT MANUALLY. Re-generate via HardKas IDE: 'Generate TypeScript SDK'.
 */

export interface ContractSpendReceipt {
  txId: string;
  contract: string;
  entry: string;
  to: string;
  outputSompi?: string;
  status: string;
}

export interface ContractProvider {
  spendContract(input: {
    address: string;
    contract: string;
    entry: string;
    to: string;
    args: unknown[];
    sequence?: string;
  }): Promise<ContractSpendReceipt>;
}

${entryInterfaces}

/**
 * Strongly-typed SDK wrapper for ${contract.name}
 */
export class ${className}Contract {
  public static readonly contractName = "${contract.name}";
  ${contract.lockingScript ? `public static readonly lockingScript = "${contract.lockingScript}";` : ""}

  constructor(
    public readonly address: string,
    public readonly provider?: ContractProvider
  ) {}

${entryMethods}
}
`;
}
